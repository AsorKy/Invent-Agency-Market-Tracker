"""Generate (and optionally run) the idempotent Postgres role bootstrap.

The SQL is built from ``ops/schemas.py``: extensions pgvector, postgis, pg_cron
and pg_trgm, then per schema an ``_owner`` and an ``_app`` role, schema
ownership and same-schema grants only. No cross-schema grant is ever emitted.
Relates to REQ-DAT-007 and REQ-EXT-003 and to ``ops/bootstrap_roles.sql.example``.

Usage: ``python ops/bootstrap_roles.py`` prints the SQL. With ``--db-url`` (or
``BOOTSTRAP_DATABASE_URL``) it executes the SQL through psycopg when installed.
App passwords come from ``BOOTSTRAP_PASSWORD_<SCHEMA>`` env vars; otherwise a
``CHANGE_ME_<SCHEMA>`` placeholder is written. No real secret lives in this repo.
"""

import argparse
import os
import sys
from collections.abc import Iterable, Mapping
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from ops.schemas import (  # noqa: E402
    EXTENSIONS,
    SCHEMAS,
    app_role,
    owner_role,
    validate_identifier,
)


def _literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def _create_role(role: str, options: str) -> str:
    return (
        f"    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = {_literal(role)}) THEN\n"
        f"        CREATE ROLE {role} {options};\n"
        "    END IF;\n"
    )


def _grant_owner_to_current_user(role: str) -> str:
    """Let a non-superuser connecting role use ``role`` (REQ-DAT-005).

    Hosted Postgres gives CREATEROLE without superuser; ALTER SCHEMA ... OWNER TO and
    CREATE SCHEMA ... AUTHORIZATION then need membership with SET. PostgreSQL 16+ needs
    ``WITH SET TRUE``; earlier versions use plain membership. Superusers skip it.
    """
    return (
        "    IF NOT (SELECT rolsuper FROM pg_roles WHERE rolname = current_user) THEN\n"
        "        IF current_setting('server_version_num')::int >= 160000 THEN\n"
        f"            EXECUTE 'GRANT {role} TO CURRENT_USER WITH SET TRUE';\n"
        "        ELSE\n"
        f"            EXECUTE 'GRANT {role} TO CURRENT_USER';\n"
        "        END IF;\n"
        "    END IF;\n"
    )


def generate_sql(
    schemas: Iterable[str] = SCHEMAS,
    passwords: Mapping[str, str] | None = None,
    extensions: Iterable[str] = EXTENSIONS,
) -> str:
    """Return the full idempotent bootstrap SQL for the given schemas."""
    names = [validate_identifier(s) for s in schemas]
    secrets = passwords or {}
    out = ["-- Generated by ops/bootstrap_roles.py from ops/schemas.py. Idempotent.\n"]
    for ext in extensions:
        out.append(f"CREATE EXTENSION IF NOT EXISTS {validate_identifier(ext)};\n")
    out.append("\nDO $$\nBEGIN\n")
    for s in names:
        password = secrets.get(s, f"CHANGE_ME_{s.upper()}")
        out.append(_create_role(owner_role(s), "NOLOGIN"))
        out.append(_grant_owner_to_current_user(owner_role(s)))
        out.append(_create_role(app_role(s), f"LOGIN PASSWORD {_literal(password)}"))
    out.append("END $$;\n\n")
    for s in names:
        out.append(f"CREATE SCHEMA IF NOT EXISTS {s};\n")
        out.append(f"ALTER SCHEMA {s} OWNER TO {owner_role(s)};\n")
    out.append(f"\nREVOKE ALL ON SCHEMA {', '.join(names)} FROM PUBLIC;\n\n")
    for s in names:
        o, a = owner_role(s), app_role(s)
        out.append(f"GRANT USAGE ON SCHEMA {s} TO {a};\n")
        out.append(f"GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA {s} TO {a};\n")
        out.append(f"GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA {s} TO {a};\n")
        out.append(
            f"ALTER DEFAULT PRIVILEGES FOR ROLE {o} IN SCHEMA {s}\n"
            f"    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO {a};\n"
        )
        out.append(
            f"ALTER DEFAULT PRIVILEGES FOR ROLE {o} IN SCHEMA {s}\n"
            f"    GRANT USAGE, SELECT, UPDATE ON SEQUENCES TO {a};\n"
        )
    return "".join(out)


def passwords_from_env(schemas: Iterable[str] = SCHEMAS) -> dict[str, str]:
    """Read ``BOOTSTRAP_PASSWORD_<SCHEMA>`` variables for the given schemas."""
    found: dict[str, str] = {}
    for s in schemas:
        value = os.environ.get(f"BOOTSTRAP_PASSWORD_{s.upper()}")
        if value:
            found[s] = value
    return found


def execute(db_url: str, sql: str) -> None:
    """Run the SQL on ``db_url`` with psycopg (imported lazily, optional)."""
    import psycopg  # type: ignore[import-not-found,unused-ignore]

    with psycopg.connect(db_url, autocommit=True) as conn:
        conn.execute(sql)


def execute_tolerant(
    db_url: str, passwords: Mapping[str, str], extensions: Iterable[str] = EXTENSIONS
) -> list[str]:
    """Create extensions one by one, then run the role SQL; return missing extensions.

    A platform that does not let this role create an extension (hosted Postgres) gets
    the name reported instead of a crash; the platform must enable it in its dashboard.
    """
    import psycopg  # type: ignore[import-not-found,unused-ignore]

    missing: list[str] = []
    with psycopg.connect(db_url, autocommit=True) as conn:
        for ext in extensions:
            try:
                conn.execute(f"CREATE EXTENSION IF NOT EXISTS {validate_identifier(ext)}")
            except psycopg.Error:
                missing.append(ext)
        conn.execute(generate_sql(passwords=passwords, extensions=()))
    return missing


def main(argv: list[str] | None = None) -> int:
    """Print the SQL, or execute it when a database URL is supplied."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--db-url", default=os.environ.get("BOOTSTRAP_DATABASE_URL"))
    args = parser.parse_args(argv)
    sql = generate_sql(passwords=passwords_from_env())
    if args.db_url:
        missing = execute_tolerant(args.db_url, passwords_from_env())
        if missing:
            print(
                "Extensions the platform must enable: " + ", ".join(missing),
                file=sys.stderr,
            )
        print("Role bootstrap applied")
    else:
        print(sql)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
