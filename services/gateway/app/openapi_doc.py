"""Render the gateway OpenAPI document from the public route registry.

``build_openapi`` turns ``registry.PUBLIC_ROUTES`` into an OpenAPI 3.1 dict:
paths under ``/api/v1``, request and response schemas generated by Pydantic,
shared error bodies, and the headers ``X-As-Of``, ``X-Brief-Cache``, ``ETag``,
``Idempotency-Key`` and ``If-Match`` where a route uses them. The output depends
only on the registry and the models, so ``ops/export_openapi.py`` writes the
same bytes on every run. It relates to ``routes.py`` (the table the gateway
serves) and the frontend type generation described in ADR-IMT-0001 section 12.6.
"""

import json
from typing import Any, Literal

from pydantic import BaseModel
from pydantic.json_schema import models_json_schema

from services.gateway.app.registry import PUBLIC_ROUTES, ErrorBody, Param, PublicRoute

API_PREFIX = "/api/v1"
DOCUMENT_VERSION = "1.0.0"
REF = "#/components/schemas/{model}"

HEADERS: dict[str, dict[str, Any]] = {
    "X-As-Of": {
        "description": "Epoch milliseconds of the data behind the response.",
        "schema": {"type": "integer", "minimum": 0},
    },
    "X-Brief-Cache": {
        "description": "Cache state of the brief: hit, stale, or miss.",
        "schema": {"type": "string"},
    },
    "ETag": {
        "description": "Entity version for optimistic concurrency.",
        "schema": {"type": "string"},
    },
    "Cache-Control": {
        "description": "Browser cache policy.",
        "schema": {"type": "string"},
    },
}
REQUEST_HEADERS: dict[str, dict[str, Any]] = {
    "Idempotency-Key": {
        "required": True,
        "description": "Unique key per logical write; a retry replays the stored response.",
        "schema": {"type": "string", "minLength": 1, "maxLength": 200},
    },
    "If-Match": {
        "required": False,
        "description": "ETag of the version being replaced.",
        "schema": {"type": "string"},
    },
}
ERROR_TEXT = {
    400: "Invalid cursor or parameter",
    401: "Authentication required",
    403: "Forbidden or CSRF token invalid",
    404: "Not found",
    409: "Conflict",
    412: "Stale ETag",
    413: "Payload too large",
    422: "Validation error",
    429: "Rate limit exceeded",
    501: "Not implemented yet",
    502: "Upstream failure",
    503: "Upstream unavailable",
    504: "Upstream timeout",
}


def _models() -> list[type[BaseModel]]:
    seen: dict[str, type[BaseModel]] = {}
    for route in PUBLIC_ROUTES:
        for model in (route.request, route.response):
            if model is None:
                continue
            existing = seen.setdefault(model.__name__, model)
            if existing is not model:
                raise ValueError(f"schema name collision: {model.__name__}")
    seen.setdefault(ErrorBody.__name__, ErrorBody)
    return [seen[name] for name in sorted(seen)]


def _param_schema(param: Param) -> dict[str, Any]:
    schema: dict[str, Any] = {"type": param.type}
    if param.minimum is not None:
        schema["minimum"] = param.minimum
    if param.maximum is not None:
        schema["maximum"] = param.maximum
    if param.default is not None:
        schema["default"] = param.default
    if param.enum:
        schema["enum"] = list(param.enum)
    return schema


def _parameters(route: PublicRoute) -> list[dict[str, Any]]:
    params: list[dict[str, Any]] = []
    for part in route.path.split("/"):
        if part.startswith("{"):
            params.append(
                {
                    "name": part.strip("{}"),
                    "in": "path",
                    "required": True,
                    "schema": {"type": "string"},
                }
            )
    for query in route.query:
        item: dict[str, Any] = {
            "name": query.name,
            "in": "query",
            "required": query.required,
            "schema": _param_schema(query),
        }
        if query.description:
            item["description"] = query.description
        params.append(item)
    for name in route.request_headers:
        params.append({"name": name, "in": "header", **REQUEST_HEADERS[name]})
    return params


def _operation(route: PublicRoute, refs: dict[tuple[str, str], str]) -> dict[str, Any]:
    ok: dict[str, Any] = {"description": "Successful response"}
    if route.response is not None:
        ok["content"] = {
            "application/json": {
                "schema": {"$ref": refs[(route.response.__name__, "serialization")]}
            }
        }
    if route.response_headers:
        ok["headers"] = {
            name: {k: v for k, v in HEADERS[name].items()} for name in route.response_headers
        }
    responses: dict[str, Any] = {str(route.status): ok}
    error_ref = {"$ref": refs[(ErrorBody.__name__, "serialization")]}
    for status in sorted(set(route.errors)):
        responses[str(status)] = {
            "description": ERROR_TEXT[status],
            "content": {"application/json": {"schema": error_ref}},
        }
    operation: dict[str, Any] = {
        "operationId": route.operation_id,
        "summary": route.summary,
        "tags": [route.tag],
        "parameters": _parameters(route),
        "responses": dict(sorted(responses.items())),
    }
    if not route.public:
        operation["security"] = [{"sessionCookie": []}]
    else:
        operation["security"] = []
    if route.request is not None:
        operation["requestBody"] = {
            "required": True,
            "content": {
                route.request_content: {
                    "schema": {"$ref": refs[(route.request.__name__, "validation")]}
                }
            },
        }
    elif route.request_content != "application/json":
        operation["requestBody"] = {
            "required": True,
            "content": {route.request_content: {"schema": {"type": "string", "format": "binary"}}},
        }
    return operation


def build_openapi() -> dict[str, Any]:
    """Return the OpenAPI document for every route in the registry."""

    models = _models()
    modes: tuple[Literal["validation", "serialization"], ...] = ("validation", "serialization")
    keys = [(model, mode) for model in models for mode in modes]
    ref_map, definitions = models_json_schema(keys, ref_template=REF)
    refs: dict[tuple[str, str], str] = {
        (model.__name__, mode): ref_map[(model, mode)]["$ref"] for model, mode in keys
    }
    paths: dict[str, dict[str, Any]] = {}
    for route in sorted(PUBLIC_ROUTES, key=lambda r: (r.path, r.method)):
        paths.setdefault(API_PREFIX + route.path, {})[route.method.lower()] = _operation(
            route, refs
        )
    return {
        "openapi": "3.1.0",
        "info": {
            "title": "Invent Market Tracker Gateway",
            "version": DOCUMENT_VERSION,
            "description": "Public API served under /api/v1. Internal routes are never exposed.",
        },
        "servers": [{"url": "/"}],
        "paths": paths,
        "components": {
            "schemas": definitions.get("$defs", {}),
            "securitySchemes": {
                "sessionCookie": {"type": "apiKey", "in": "cookie", "name": "__Host-session"}
            },
        },
    }


def render_openapi() -> str:
    """Return the canonical serialized document (sorted keys, trailing newline)."""

    return json.dumps(build_openapi(), indent=2, sort_keys=True, ensure_ascii=True) + "\n"
